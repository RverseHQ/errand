const languageButton = document.getElementById("language-button");
const languageOptions = document.getElementById("language-options");
let currentLanguage = "en";

window.errandText = (key) => (translations[currentLanguage] || translations.en)[key] || translations.en[key];

function setLanguage(language) {
  currentLanguage = translations[language] ? language : "en";
  const strings = translations[currentLanguage];
  const meta = languageMeta[currentLanguage];

  document.documentElement.lang = meta.htmlLang;
  document.title = meta.title;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.getAttribute("data-i18n");
    element.textContent = strings[key] || translations.en[key] || "";
  });

  document.querySelectorAll("[data-i18n-html]").forEach((element) => {
    const key = element.getAttribute("data-i18n-html");
    element.innerHTML = strings[key] || translations.en[key] || "";
  });

  document.querySelectorAll("[data-i18n-aria]").forEach((element) => {
    const key = element.getAttribute("data-i18n-aria");
    element.setAttribute("aria-label", strings[key] || translations.en[key] || "");
  });

  languageButton.textContent = meta.button;
  document.dispatchEvent(new Event("errand:lang"));
}

function setLanguageMenuOpen(isOpen) {
  languageOptions.hidden = !isOpen;
  languageButton.setAttribute("aria-expanded", String(isOpen));
}

languageButton.addEventListener("click", () => {
  setLanguageMenuOpen(languageOptions.hidden);
});

languageOptions.addEventListener("click", (event) => {
  const option = event.target.closest("[data-language-option]");

  if (!option) {
    return;
  }

  setLanguage(option.getAttribute("data-language-option"));
  setLanguageMenuOpen(false);
});

document.addEventListener("click", (event) => {
  if (!event.target.closest(".language")) {
    setLanguageMenuOpen(false);
  }
});

document.addEventListener("keydown", (event) => {
  if (event.key === "Escape" && !languageOptions.hidden) {
    setLanguageMenuOpen(false);
    languageButton.focus();
  }
});

setLanguage("en");
